// 把顯示文字裡「連續三個以上的換行」收斂成一個空行。
//
// 為什麼需要：字幕用 white-space: pre-wrap（canvas-styles.tsx），換行原樣保留。
// 實際抓到的字串是
//
//   '…後端也沒有錯誤。不過……\n\n\n\n這一切，都是因為你決定要關掉「我」…'
//
// 畫面上就是三行高的空白，看起來像少了一段內容或畫面壞掉。
//
// 四個換行有兩個來源，修法一樣：
//   1. 模型自己在段尾與下一段段首各打了 '\n\n'，串接起來變四個。
//   2. transformers.balance_asterisk_actions 刪掉「只包住空白的星號對」時，
//      連同中間空白一起刪，但兩側原本的換行留著，於是 '\n\n' + '\n\n' 併成四個。
//
// 為什麼在前端做而不是後端：後端是一段一段處理的，段尾的 '\n\n' 與下一段段首的
// '\n\n' 在任何單一段裡都看不到，只有串接之後才成立——而串接發生在這裡。
//
// 保留一個空行（'\n\n'）而不是全部壓成單一換行：模型有時真的在分段，那個停頓
// 是有意義的，只是不該佔三行。
export function collapseBlankLines(text: string): string {
  if (!text) return text;
  // \r\n 一併處理，免得 Windows 來源的文字漏掉。
  return text.replace(/\r\n/g, '\n').replace(/\n{3,}/g, '\n\n');
}
